#!/usr/bin/env python3
"""Download the site's fonts (Latin subset, variable WOFF2) into assets/fonts and write assets/css/fonts.css.
Fonts: Fraunces and Inter Tight — SIL Open Font License 1.1 (Google Fonts). Run once; needs curl + network."""
import pathlib, re, subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36"
FAMILIES = {
    "inter-tight": ("Inter Tight", "https://fonts.googleapis.com/css2?family=Inter+Tight:wght@100..900&display=swap"),
    "fraunces": ("Fraunces", "https://fonts.googleapis.com/css2?family=Fraunces:ital,opsz,wght@0,9..144,300..800;1,9..144,300..800&display=swap"),
}
get = lambda u: subprocess.run(["curl", "-sSfL", "-A", UA, u], check=True, capture_output=True).stdout

out = ["/* Fraunces & Inter Tight — SIL Open Font License 1.1. Generated by tools/fetch-fonts.py */"]
(ROOT / "assets/fonts").mkdir(parents=True, exist_ok=True)
for slug, (family, url) in FAMILIES.items():
    css = get(url).decode()
    for subset, body in re.findall(r"/\* ([\w-]+) \*/\s*@font-face\s*{([^}]*)}", css):
        if subset != "latin":
            continue
        style = re.search(r"font-style:\s*(\w+)", body).group(1)
        weight = re.search(r"font-weight:\s*([\d ]+);", body).group(1).strip()
        src = re.search(r"url\(([^)]+)\)", body).group(1)
        rng = re.search(r"unicode-range:\s*([^;]+);", body).group(1).strip()
        name = f"{slug}-latin{'-italic' if style == 'italic' else ''}.woff2"
        (ROOT / "assets/fonts" / name).write_bytes(get(src))
        out.append(f'@font-face{{font-family:"{family}";font-style:{style};font-weight:{weight};font-display:swap;src:url("../fonts/{name}") format("woff2");unicode-range:{rng}}}')
(ROOT / "assets/css/fonts.css").write_text("\n".join(out) + "\n", encoding="utf-8")
print("\n".join(out[1:]))
